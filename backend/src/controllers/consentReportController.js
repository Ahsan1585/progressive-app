// Consent-scoped "disclosure packet" — GET /api/patients/:id/consents/:consentId/report.
//
// When a parent has approved a records release (a records_consents row,
// FERPA 34 CFR 99.30 / IDEA Part C 303.414), staff generate one PDF holding
// ONLY what that consent approves, plus a copy of the consent itself, to hand
// to the named recipient. Generating it does not send it anywhere, so the
// audit event (and the child's Record of Disclosures) says "prepared".
//
// The full record export (patientRecordExportController.exportPatientRecord)
// is unchanged and remains the parent's own copy. Its single-child section
// builders are reused here, so both documents render sessions, SEVFs and
// invoice lines identically, with the same exclusions: every section is
// generated fresh from this one patient_id (never a stored multi-child batch
// file) and the stored invoice PDF, which carries the practitioner's SSN/EIN,
// is never used.
const { PDFDocument, rgb, StandardFonts } = require('pdf-lib');
const { pool } = require('../config/db');
const { logAudit } = require('../utils/auditLog');
const { getCompanyName } = require('../utils/companyName');
const { isValidIntId } = require('../utils/consentValidation');
const { safeFilenamePart } = require('../utils/pdfText');
const {
  pdfSafeText,
  drawRedisclosureNotice,
  drawSessionLogSection,
  appendSevfSection,
  drawBillingSection,
  wrapText,
  formatDateOnly,
  formatTimestampDate,
  RECORD_TYPE_LABELS,
  NJ_TZ,
  PAGE,
  MARGIN,
  CONTENT_WIDTH,
} = require('./patientRecordExportController');

const NOT_FOUND = { error: 'Consent not found.' };
const NOT_ACTIVE = { error: 'This consent is revoked or expired, so a report cannot be generated.' };

const DARK = rgb(0.08, 0.1, 0.15);
const TEXT = rgb(0.2, 0.24, 0.3);
const MUTED = rgb(0.4, 0.46, 0.55);
const RULE = rgb(0.85, 0.87, 0.9);

// Section keys in packet order. full_record_export means all three record
// sections. Deliberately absent from EVERY disclosure packet: the internal
// Record Access History, Record of Disclosures and Consents on File. Those
// exist for the parent's own inspection (34 CFR 303.405/.406) via the full
// export, and are not records the parent approved releasing to a third party.
const SECTION_ORDER = ['session_logs', 'sevf_forms', 'invoices'];
function sectionsForRecordTypes(recordTypes) {
  const types = new Set(Array.isArray(recordTypes) ? recordTypes : []);
  if (types.has('full_record_export')) return [...SECTION_ORDER];
  return SECTION_ORDER.filter((t) => types.has(t));
}

const EMPTY_SECTION = {
  session_logs: { title: 'Session Log Summary', message: 'No session logs on file for this child.' },
  sevf_forms: { title: 'Service Encounter Verification Forms (SEVF)', message: 'No SEVF forms on file for this child.' },
  invoices: { title: 'Billing Summary', message: 'No invoices on file for this child.' },
};

const IDENTITY_METHOD_LABELS = {
  known_parent: 'Known parent/guardian',
  photo_id: 'Photo ID checked',
  callback_verified: 'Verified by callback',
  in_person: 'Verified in person',
  other: 'Other',
};

// Node's ICU puts a narrow no-break space before AM/PM, which WinAnsi lacks.
const safe = (text) => pdfSafeText(String(text ?? '').replace(/[  ]/g, ' '));
const recordLabels = (types) => (Array.isArray(types) && types.length
  ? types.map((t) => RECORD_TYPE_LABELS[t] || t).join(', ')
  : '—');
const formatDateTime = (value) => {
  if (!value) return '—';
  const d = new Date(value);
  if (Number.isNaN(d.getTime())) return '—';
  return d.toLocaleString('en-US', {
    timeZone: NJ_TZ, month: 'long', day: 'numeric', year: 'numeric', hour: 'numeric', minute: '2-digit', timeZoneName: 'short',
  });
};
const formatDob = (dob) => {
  const iso = formatDateOnly(dob);
  return iso !== '—' ? iso : (dob ? String(dob) : '—');
};
const fullName = (p) => (p ? `${p.first_name || ''} ${p.last_name || ''}`.trim() : '');
const MAX_DEVICE_LENGTH = 160;

function recipientSlug(name) {
  const slug = String(name || '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 40).replace(/-+$/, '');
  return slug || 'recipient';
}

function buildCoverRows({ patient, consent, companyName, generatedBy, generatedAt = new Date() }) {
  return [
    ['Child:', fullName(patient) || '—'],
    ['Date of birth:', formatDob(patient.dob)],
    ['Child ID:', patient.child_id || '—'],
    ['Prepared for:', consent.recipient_name || '—'],
    ['Purpose:', consent.purpose || '—'],
    ['Records included:', recordLabels(consent.record_types)],
    ['Consent valid through:', formatTimestampDate(consent.expires_at)],
    ['Agency:', companyName || '—'],
    ['Generated:', formatDateTime(generatedAt)],
    ['Generated by:', generatedBy || '—'],
  ].map(([label, value]) => [label, safe(value)]);
}

// The signed-consent copy as plain data (drawn by drawConsentCopyPage).
// Nothing here is invented: missing provenance is reported as missing.
function buildConsentCopy(consent, { grantedByName } = {}) {
  const staff = grantedByName || 'agency staff';
  const recipient = consent.recipient_email && consent.recipient_email !== consent.recipient_name
    ? `${consent.recipient_name || '—'} <${consent.recipient_email}>`
    : (consent.recipient_name || consent.recipient_email || '—');
  const method = consent.source === 'electronic' || consent.source === 'paper' ? consent.source : 'legacy';
  const rows = [
    ['Shared with:', recipient],
    ['Purpose:', consent.purpose || '—'],
    ['Records approved:', recordLabels(consent.record_types)],
    ['Valid from:', consent.signed_on ? formatDateOnly(consent.signed_on) : formatTimestampDate(consent.granted_at)],
    ['Valid through:', formatTimestampDate(consent.expires_at)],
  ];
  let signature = null;

  if (method === 'electronic') {
    signature = { name: safe(consent.signed_name || '—') };
    const ua = String(consent.signed_user_agent || '').trim();
    rows.push(
      ['How obtained:', 'Electronic signature'],
      ['Signed:', formatDateTime(consent.granted_at)],
      ['IP address:', consent.signed_ip || 'Not recorded'],
      ['Device:', ua ? (ua.length > MAX_DEVICE_LENGTH ? `${ua.slice(0, MAX_DEVICE_LENGTH - 1)}…` : ua) : 'Not recorded'],
      ['Identity verified by:', 'Electronic signature, child date of birth verified'],
      ['Attestation:', consent.attestation_text || 'Attestation wording was not recorded for this consent'],
    );
  } else if (method === 'paper') {
    const idLabel = IDENTITY_METHOD_LABELS[consent.identity_verified_method] || consent.identity_verified_method || 'Not recorded';
    rows.push(
      ['How obtained:', `Paper consent signed on ${formatDateOnly(consent.signed_on)}, confirmed on file by ${staff}`],
      ['Identity verified by:', consent.identity_verified_note ? `${idLabel}: ${consent.identity_verified_note}` : idLabel],
      ['Proof note:', consent.proof_note || '—'],
      ['Attestation:', 'Paper consent confirmed on file by the agency'],
    );
  } else {
    // source NULL: logged by staff before e-signing / paper attestation existed.
    rows.push(
      ['How obtained:', `Recorded by ${staff} before electronic signing was available`],
      ['Proof note:', consent.proof_note || '—'],
      ['Attestation:', 'Attestation wording was not recorded for this consent'],
    );
  }
  rows.push(['Consent ID:', String(consent.id)]);

  return {
    title: 'Parental consent record',
    method,
    signature,
    rows: rows.map(([label, value]) => [label, safe(value)]),
  };
}

// Label/value rows with wrapping and simple page overflow.
function makeWriter(pdfDoc, fonts, continuedTitle) {
  const state = { page: pdfDoc.addPage([PAGE.width, PAGE.height]), y: PAGE.height - 60 };
  state.ensure = (h) => {
    if (state.y - h < MARGIN + 20) {
      state.page = pdfDoc.addPage([PAGE.width, PAGE.height]);
      state.y = PAGE.height - MARGIN;
      state.page.drawText(`${continuedTitle} (continued)`, { x: MARGIN, y: state.y, font: fonts.bold, size: 11, color: DARK });
      state.y -= 24;
    }
  };
  state.row = (label, value, labelWidth = 150) => {
    const lines = wrapText(value, fonts.regular, 10.5, CONTENT_WIDTH - labelWidth);
    state.ensure(lines.length * 14 + 6);
    state.page.drawText(label, { x: MARGIN, y: state.y, font: fonts.bold, size: 10.5, color: TEXT });
    lines.forEach((line, i) => {
      state.page.drawText(line, { x: MARGIN + labelWidth, y: state.y - i * 14, font: fonts.regular, size: 10.5, color: TEXT });
    });
    state.y -= lines.length * 14 + 6;
  };
  return state;
}

function drawPacketCover(pdfDoc, coverRows, fonts) {
  const w = makeWriter(pdfDoc, fonts, 'Records disclosure packet');
  w.y = PAGE.height - 90;
  w.page.drawText('Records disclosure packet', { x: MARGIN, y: w.y, font: fonts.bold, size: 20, color: DARK });
  w.y -= 36;
  coverRows.forEach(([label, value]) => w.row(label, value));

  w.y -= 8;
  w.ensure(260);
  w.page.drawLine({ start: { x: MARGIN, y: w.y }, end: { x: PAGE.width - MARGIN, y: w.y }, thickness: 0.5, color: RULE });
  w.y -= 22;
  const note = 'This packet was prepared under the parental consent copied on the next page. It contains only the '
    + 'records that consent approves for the recipient named above, for the stated purpose.';
  wrapText(note, fonts.regular, 9.5, CONTENT_WIDTH).forEach((line) => {
    w.page.drawText(line, { x: MARGIN, y: w.y, font: fonts.regular, size: 9.5, color: MUTED });
    w.y -= 14;
  });
  w.y -= 16;
  // Redisclosure notice (34 CFR 99.33 / 303.414) accompanies every disclosure.
  drawRedisclosureNotice(w.page, w.y, fonts);
  return w.page;
}

async function drawConsentCopyPage(pdfDoc, copy, fonts) {
  const italic = await pdfDoc.embedFont(StandardFonts.TimesRomanItalic);
  const w = makeWriter(pdfDoc, fonts, copy.title);
  w.y = PAGE.height - MARGIN - 10;
  w.page.drawText(copy.title, { x: MARGIN, y: w.y, font: fonts.bold, size: 18, color: DARK });
  w.y -= 18;
  w.page.drawText('Copy of the consent authorizing this disclosure (34 CFR 99.30 / 303.414).', { x: MARGIN, y: w.y, font: fonts.regular, size: 9.5, color: MUTED });
  w.y -= 26;

  copy.rows.forEach(([label, value]) => {
    w.row(label, value);
    if (label === 'How obtained:' && copy.signature) {
      w.ensure(56);
      w.y -= 8;
      w.page.drawText('Signature:', { x: MARGIN, y: w.y, font: fonts.bold, size: 10.5, color: TEXT });
      w.page.drawText(copy.signature.name, { x: MARGIN + 156, y: w.y, font: italic, size: 20, color: DARK });
      w.y -= 6;
      w.page.drawLine({ start: { x: MARGIN + 150, y: w.y }, end: { x: MARGIN + 430, y: w.y }, thickness: 0.75, color: MUTED });
      w.y -= 12;
      w.page.drawText('Typed by the parent/guardian as their electronic signature', { x: MARGIN + 150, y: w.y, font: fonts.regular, size: 8, color: MUTED });
      w.y -= 22;
    }
  });
  return w.page;
}

// Just the signed-consent copy page, for the parent's own download. Contains
// nothing but the consent itself (no child records).
async function buildConsentCopyPdf({ consent, grantedByName }) {
  const doc = await PDFDocument.create();
  const fonts = {
    regular: await doc.embedFont(StandardFonts.Helvetica),
    bold: await doc.embedFont(StandardFonts.HelveticaBold),
  };
  await drawConsentCopyPage(doc, buildConsentCopy(consent, { grantedByName }), fonts);
  return doc.save();
}

function drawEmptySectionPage(pdfDoc, { title, message }, fonts) {
  const page = pdfDoc.addPage([PAGE.width, PAGE.height]);
  page.drawText(title, { x: MARGIN, y: PAGE.height - MARGIN, font: fonts.bold, size: 14, color: DARK });
  page.drawText(message, { x: MARGIN, y: PAGE.height - MARGIN - 44, font: fonts.regular, size: 10, color: MUTED });
  return page;
}

// Names of the staff involved, looked up once: the generator and the person
// who recorded the consent.
async function loadStaffNames(staffIdCandidates) {
  const staffIds = staffIdCandidates
    .filter((v) => v != null && /^\d{1,9}$/.test(String(v)))
    .map(Number);
  const { rows } = staffIds.length
    ? await pool.query('SELECT id, first_name, last_name FROM practitioners WHERE id = ANY($1::int[])', [staffIds])
    : { rows: [] };
  return (pid) => fullName(rows.find((s) => Number(s.id) === Number(pid)));
}

// Builds the packet PDF bytes for one ACTIVE consent of `patient`: cover,
// signed-consent copy, then the approved sections. `recordTypes` narrows what
// goes in (a release may send less than the consent allows) but is always
// intersected with what the consent approves, so it can never widen it.
// Shared by the staff download (sendConsentPacket) and the recipient release
// download (recordsReleaseController).
async function buildConsentPacketPdf({ patient, consent, recordTypes, generatedBy, grantedByName, now = new Date() }) {
  const approved = new Set(sectionsForRecordTypes(consent.record_types));
  const wanted = recordTypes ? new Set(sectionsForRecordTypes(recordTypes)) : approved;
  const sections = SECTION_ORDER.filter((t) => approved.has(t) && wanted.has(t));
  const companyName = await getCompanyName();

  let assessments = [];
  if (sections.length) {
    ({ rows: assessments } = await pool.query(
      'SELECT * FROM assessments WHERE patient_id = $1 ORDER BY service_date ASC, start_time ASC',
      [String(patient.id)]
    ));
  }

  const outDoc = await PDFDocument.create();
  const fonts = {
    regular: await outDoc.embedFont(StandardFonts.Helvetica),
    bold: await outDoc.embedFont(StandardFonts.HelveticaBold),
  };

  const coverConsent = { ...consent, record_types: sections.length ? sections : consent.record_types };
  drawPacketCover(outDoc, buildCoverRows({ patient, consent: coverConsent, companyName, generatedBy, generatedAt: now }), fonts);
  await drawConsentCopyPage(outDoc, buildConsentCopy(consent, { grantedByName }), fonts);

  for (const section of sections) {
    if (assessments.length === 0) {
      drawEmptySectionPage(outDoc, EMPTY_SECTION[section], fonts);
    } else if (section === 'session_logs') {
      drawSessionLogSection(outDoc, assessments, fonts);
    } else if (section === 'sevf_forms') {
      // Unlike the full export, a failure here fails the request: a packet
      // must never silently omit a section the parent approved.
      await appendSevfSection(outDoc, assessments, patient, companyName);
    } else if (section === 'invoices') {
      drawBillingSection(outDoc, assessments, fonts);
    }
  }
  return outDoc.save();
}

// Builds the packet for one ACTIVE consent of `patient` and sends it. Shared
// with patientRecordExportController.exportPatientRecord, which returns this
// packet (not the parent's complete copy) when a covering consent exists.
// The caller has already verified the consent belongs to this patient and is
// active. The PDF is built and the headers set BEFORE the audit row is
// written, so a failure can never leave a false disclosure entry; errors
// propagate to the caller's 500 handler.
async function sendConsentPacket(req, res, { patient, consent, now = new Date() }) {
  const id = String(patient.id);
  const staffName = await loadStaffNames([req.practitioner?.practitionerId, consent.granted_by]);
  const generatedBy = staffName(req.practitioner?.practitionerId) || req.practitioner?.email || 'Unknown';

  const pdfBytes = await buildConsentPacketPdf({
    patient, consent, generatedBy, grantedByName: staffName(consent.granted_by), now,
  });

  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader('Content-Disposition', `attachment; filename="consent-report-${safeFilenamePart(patient.last_name)}-${recipientSlug(consent.recipient_name)}.pdf"`);
  res.setHeader('Cache-Control', 'no-store');

  // Recipient organization and purpose only; no child names.
  logAudit({
    req, action: 'consent_report_generated', resourceType: 'patient', resourceId: id,
    details: { consentId: consent.id, recordTypes: consent.record_types, recipient: consent.recipient_name, purpose: consent.purpose },
  });

  res.send(Buffer.from(pdfBytes));
}

const generateConsentReport = async (req, res) => {
  const { id, consentId } = req.params;
  if (!isValidIntId(id) || !isValidIntId(consentId)) return res.status(404).json(NOT_FOUND);

  try {
    // Scoped by BOTH ids: another child's consent id is simply not found.
    const { rows: consentRows } = await pool.query(
      'SELECT * FROM records_consents WHERE id = $1 AND patient_id = $2',
      [consentId, id]
    );
    const consent = consentRows[0];
    if (!consent) return res.status(404).json(NOT_FOUND);
    const now = new Date();
    if (consent.revoked_at || (consent.expires_at && new Date(consent.expires_at) <= now)) {
      return res.status(409).json(NOT_ACTIVE);
    }

    const { rows: patientRows } = await pool.query('SELECT * FROM patients WHERE id = $1', [id]);
    const patient = patientRows[0];
    if (!patient) return res.status(404).json({ error: 'Child not found' });

    await sendConsentPacket(req, res, { patient, consent, now });
  } catch (error) {
    console.error('generateConsentReport error:', error);
    res.status(500).json({ error: 'Failed to generate the disclosure packet' });
  }
};

